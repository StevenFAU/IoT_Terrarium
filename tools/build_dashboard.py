#!/usr/bin/env python3
"""Packs the dashboard (../dashboard) into terrarium_receiver/web_assets.h so the receiver board can serve it.

Run this after changing anything in dashboard/, then re-upload terrarium_receiver:

    python3 tools/build_dashboard.py

Each file is gzip-compressed and stored as a byte array in flash. demo.js is left out: the board never runs in
demo mode. Standard library only.
"""
import gzip
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "dashboard"
OUTPUT = ROOT / "terrarium_receiver" / "web_assets.h"

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".webmanifest": "application/manifest+json",
}
SKIP = {"demo.js"}


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    files = sorted(p for p in SOURCE.iterdir() if p.is_file() and p.suffix in MIME and p.name not in SKIP)
    digest = hashlib.sha256()
    arrays, entries, total_raw, total_gz = [], [], 0, 0
    for i, path in enumerate(files):
        raw = path.read_bytes()
        packed = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0 keeps the output identical between builds
        digest.update(path.name.encode() + raw)
        arrays.append(c_array(f"WEB_ASSET_{i}", packed))
        entries.append(f'  {{"/{path.name}", "{MIME[path.suffix]}", WEB_ASSET_{i}, {len(packed)}}},')
        total_raw += len(raw)
        total_gz += len(packed)
        print(f"  {path.name:24} {len(raw):7,} bytes -> {len(packed):7,} gzipped")

    etag = digest.hexdigest()[:16]
    OUTPUT.write_text(
        "// Generated by tools/build_dashboard.py from ../dashboard. Don't edit by hand: change the dashboard and\n"
        "// re-run the script.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "struct WebAsset {\n  const char *path;\n  const char *mime;\n  const uint8_t *data;\n  size_t length;\n};\n\n"
        + "\n".join(arrays)
        + "\nstatic const WebAsset WEB_ASSETS[] = {\n" + "\n".join(entries) + "\n};\n"
        + f"static const size_t WEB_ASSET_COUNT = {len(files)};\n"
        + f'#define WEB_ASSETS_ETAG "\\"{etag}\\""\n'
    )
    print(f"{len(files)} files, {total_raw:,} bytes -> {total_gz:,} gzipped. Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
